void init_obj_theme_array(obj_theme_array_t *a) {
    a->used            = 0;
    a->size            = 0;
    a->amount_elements = 0;
}

void add_obj_theme_array(obj_theme_array_t *a, ui_styles_t *element) {
    if (a->used == a->size) {
        a->size  = (a->size * 3) / 2 + 8;
        a->array = realloc(a->array, a->size * sizeof(ui_styles_t *));
    }
    a->array[a->used++] = element;
    a->amount_elements++;
}


